import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const outputFile = path.join(rootDir, "src", "legacy-app.js");
const sourceFiles = [
  path.join(rootDir, "src", "data.js"),
  path.join(rootDir, "src", "sim.js"),
  path.join(rootDir, "src", "render.js"),
  path.join(rootDir, "src", "ui.js"),
];

async function main() {
  const parts = await Promise.all(
    sourceFiles.map(async (filename) => {
      const content = await fs.readFile(filename, "utf8");
      return content.replace(/^\uFEFF/, "");
    })
  );

  const body = parts.map((part) => part.trimEnd()).join("\n\n");
  const output = `// Generated by scripts/build-legacy-app.mjs.\n// Edit src/data.js, src/sim.js, src/render.js, or src/ui.js and rebuild instead of editing this file directly.\n(() => {\n'use strict';\n\n${body}\n\n})();\n`;

  await fs.writeFile(outputFile, output, "utf8");
  console.log(
    `Built ${path.relative(rootDir, outputFile)} from ${sourceFiles
      .map((filename) => path.relative(rootDir, filename))
      .join(", ")}.`
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
